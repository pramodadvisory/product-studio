"use client"

import * as React from "react"
import { SendIcon, SparklesIcon, FileTextIcon } from "lucide-react"

import { cn } from "@/lib/utils"
import { Button } from "@/components/ui/button"
import { Textarea } from "@/components/ui/textarea"
import type { DocNode } from "@/hooks/use-docs"

type Message = {
  id: string
  role: "user" | "assistant"
  content: string
}

type DocsChatProps = {
  doc: DocNode | null
  /** Replace the active document's content with new HTML. */
  onApplyContent: (content: string) => void
  /** Create a new document at the root and select it. */
  onCreateDoc: (name: string, content: string) => void
}

const SUGGESTIONS = [
  "Draft an outline for this document",
  "Summarize the current content",
  "Add a conclusion section",
]

// UI-only mock. Inspects the prompt, performs a best-effort edit on the active
// document, and returns a short explanation. Replace with a real Claude API
// call (e.g. a /api/docs-assistant route) to get genuine edits.
function mockAssistant(
  prompt: string,
  doc: DocNode | null,
  actions: Pick<DocsChatProps, "onApplyContent" | "onCreateDoc">
): string {
  const p = prompt.toLowerCase()

  if (/(create|new) (a )?(doc|document|file|page)/.test(p)) {
    const name = "AI Document.md"
    actions.onCreateDoc(
      name,
      `<h1>${escapeHtml(prompt.replace(/.*?(doc|document|file|page)\s*/i, "").trim() || "New Document")}</h1><p>Draft created by the assistant. Refine it here or ask for more changes.</p>`
    )
    return `Created a new document "${name}" and selected it. (Demo response — connect the Claude API to generate real content.)`
  }

  if (!doc) {
    return "Select a document on the left first, then I can help you edit it. (Demo response — no LLM connected yet.)"
  }

  if (/outline|structure/.test(p)) {
    actions.onApplyContent(
      `<h1>${escapeHtml(doc.name.replace(/\.md$/, ""))}</h1><h2>Overview</h2><p>Brief summary of the document.</p><h2>Details</h2><ul><li>Point one</li><li>Point two</li><li>Point three</li></ul><h2>Next steps</h2><p>What happens next.</p>`
    )
    return "I drafted an outline and applied it to the document. (Demo response — wire up the Claude API for tailored content.)"
  }

  if (/conclusion|summary|wrap.?up/.test(p)) {
    const current = doc.content ?? ""
    actions.onApplyContent(
      `${current}<h2>Conclusion</h2><p>Summary paragraph generated by the assistant.</p>`
    )
    return "Added a conclusion section to the end of the document. (Demo response — connect the Claude API for a real summary.)"
  }

  return `As your docs assistant, I'd edit "${doc.name}" based on: "${prompt}". (Demo response — no LLM connected yet. Wire this up to the Claude API to apply real edits.)`
}

function escapeHtml(s: string) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
}

export function DocsChat({ doc, onApplyContent, onCreateDoc }: DocsChatProps) {
  const [messages, setMessages] = React.useState<Message[]>([])
  const [input, setInput] = React.useState("")
  const [thinking, setThinking] = React.useState(false)
  const scrollRef = React.useRef<HTMLDivElement>(null)

  React.useEffect(() => {
    scrollRef.current?.scrollTo({
      top: scrollRef.current.scrollHeight,
      behavior: "smooth",
    })
  }, [messages, thinking])

  function send(text: string) {
    const trimmed = text.trim()
    if (!trimmed || thinking) return

    const userMessage: Message = {
      id: crypto.randomUUID(),
      role: "user",
      content: trimmed,
    }
    setMessages((prev) => [...prev, userMessage])
    setInput("")
    setThinking(true)

    window.setTimeout(() => {
      const reply = mockAssistant(trimmed, doc, {
        onApplyContent,
        onCreateDoc,
      })
      setMessages((prev) => [
        ...prev,
        { id: crypto.randomUUID(), role: "assistant", content: reply },
      ])
      setThinking(false)
    }, 700)
  }

  function handleKeyDown(e: React.KeyboardEvent<HTMLTextAreaElement>) {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault()
      send(input)
    }
  }

  return (
    <div className="flex h-full flex-col">
      <div className="flex items-center gap-2 border-b px-3 py-2.5">
        <div className="flex size-7 shrink-0 items-center justify-center rounded-lg bg-muted text-foreground">
          <SparklesIcon className="size-4" />
        </div>
        <div className="min-w-0">
          <p className="truncate text-sm font-semibold">AI Assistant</p>
          <p className="truncate text-xs text-muted-foreground">
            {doc ? `Editing ${doc.name}` : "No document selected"}
          </p>
        </div>
      </div>

      <div
        ref={scrollRef}
        className="flex-1 space-y-4 overflow-y-auto px-3 py-4"
      >
        {messages.length === 0 && !thinking ? (
          <div className="flex h-full flex-col items-center justify-center gap-3 px-2 text-center">
            <FileTextIcon className="size-8 text-muted-foreground" />
            <p className="text-sm text-muted-foreground">
              Ask the assistant to draft, edit, or restructure your documents.
            </p>
            <div className="flex w-full flex-col gap-1.5">
              {SUGGESTIONS.map((s) => (
                <button
                  key={s}
                  type="button"
                  onClick={() => send(s)}
                  className="rounded-md border px-3 py-2 text-left text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-accent-foreground"
                >
                  {s}
                </button>
              ))}
            </div>
          </div>
        ) : (
          messages.map((m) => (
            <div
              key={m.id}
              className={cn(
                "flex",
                m.role === "user" ? "justify-end" : "justify-start"
              )}
            >
              <div
                className={cn(
                  "max-w-[85%] rounded-xl px-3 py-2 text-sm whitespace-pre-wrap",
                  m.role === "user"
                    ? "bg-primary text-primary-foreground"
                    : "bg-muted text-foreground"
                )}
              >
                {m.content}
              </div>
            </div>
          ))
        )}
        {thinking && (
          <div className="flex justify-start">
            <div className="rounded-xl bg-muted px-3 py-2 text-sm text-muted-foreground">
              Thinking…
            </div>
          </div>
        )}
      </div>

      <div className="border-t p-3">
        <div className="flex items-end gap-2">
          <Textarea
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={handleKeyDown}
            placeholder="Ask the assistant to edit this doc…"
            className="max-h-32 min-h-10 flex-1 resize-none"
            rows={1}
          />
          <Button
            size="icon"
            onClick={() => send(input)}
            disabled={!input.trim() || thinking}
            aria-label="Send message"
          >
            <SendIcon />
          </Button>
        </div>
      </div>
    </div>
  )
}
